    /// <summary>Цитата игрока по ситуации (win, loss, bigloss, comeback, slump, hot, chase, award, rookie).</summary>
    public static string Of(Career c, int id, string situation, Random r)
    {
        if (!Lines.TryGetValue(situation, out var by)) return null;
        var g = Group(c, id);
        var xs = by.TryGetValue(g, out var a) ? a : by["base"];
        return xs[r.Next(xs.Length)];
    }

