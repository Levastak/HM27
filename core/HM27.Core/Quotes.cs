    /// <summary>Тренер ИИ под давлением — по стилю: рисковый обещает атаку, осторожный — порядок, гибкий — перемены.</summary>
    public static string Coach(StaffMember s, string situation, Random r)
    {
        if (s == null) return null;
        string[] xs = situation switch
        {
            "hot" => s.Risk >= 1 ? new[] { "Мы будем атаковать ещё больше. Я не умею играть иначе.", "Сидеть сзади — не мой хоккей. Шайбы придут." }
                   : s.Risk <= -1 ? new[] { "Сначала надо перестать пропускать. Порядок — потом результат.", "Мы слишком открылись. Вернёмся к надёжной игре." }
                   : s.Flex >= 13 ? new[] { "Будем пробовать новое. Сидеть и ждать — не вариант.", "Я готов менять всё: звенья, систему, подход." }
                   : new[] { "Я верю в эту группу и в то, что мы делаем.", "Результаты не те, но я знаю, что мы на правильном пути." },
            "fired" => new[] { "Благодарю клуб и игроков. В этом бизнесе так бывает.", "Жаль, что не успел довести дело до конца. Удачи ребятам." },
            "new" => s.Risk >= 1 ? new[] { "Мы будем играть быстро и смело. Болельщикам понравится." } : s.Risk <= -1 ? new[] { "Первое — порядок в своей зоне. Остальное придёт." } : new[] { "Здесь хорошие игроки. Моя задача — собрать их в команду." },
            _ => new[] { "Работаем." },
        };
        return xs[r.Next(xs.Length)];
    }
